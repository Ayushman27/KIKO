import 'package:flutter/material.dart';

class LoginPairingScreen extends StatefulWidget {
  const LoginPairingScreen({super.key});

  @override
  State<LoginPairingScreen> createState() => _LoginPairingScreenState();
}

class _LoginPairingScreenState extends State<LoginPairingScreen> {
  final _tokenController = TextEditingController(text: "dev_device_token_secret_12345");

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: const Text('Device Pairing', style: TextStyle(color: Color(0xFF00F0FF))),
        backgroundColor: const Color(0xFF0F172A),
      ),
      body: Padding(
        padding: const EdgeInsets.all(20.0),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            const Text(
              'Pair Laptop Agent',
              style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold, color: Colors.white),
            ),
            const SizedBox(height: 8),
            const Text(
              'Enter the secure token generated by your Windows Background Agent.',
              style: TextStyle(color: Colors.grey, fontSize: 12),
            ),
            const SizedBox(height: 20),
            TextField(
              controller: _tokenController,
              decoration: InputDecoration(
                labelText: 'Device Pairing Token',
                labelStyle: const TextStyle(color: Color(0xFF00F0FF)),
                filled: true,
                fillColor: const Color(0xFF0F172A),
                border: OutlineInputBorder(borderRadius: BorderRadius.circular(12)),
              ),
            ),
            const SizedBox(height: 20),
            SizedBox(
              width: double.infinity,
              height: 48,
              child: ElevatedButton(
                style: ElevatedButton.styleFrom(
                  backgroundColor: const Color(0xFF00F0FF),
                  shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
                ),
                onPressed: () {
                  ScaffoldMessenger.of(context).showSnackBar(
                    const SnackBar(content: Text('Device Paired Successfully!')),
                  );
                  Navigator.pop(context);
                },
                child: const Text('Pair Device', style: TextStyle(color: Colors.black, fontWeight: FontWeight.bold)),
              ),
            ),
          ],
        ),
      ),
    );
  }
}
